#pragma once
#include <stdint.h>

/*
 * Протокол обновления прошивки Wiren Board — общая часть загрузчика,
 * приложения и хостовых утилит.
 *
 * Снято с исходников wirenboard/wb-mcu-fw-flasher, чтобы модуль обновлялся
 * штатным инструментом контроллера, без своих утилит:
 *
 *     wb-mcu-fw-flasher -j -d /dev/ttyMOD1 -a 1 -f vfd.wbfw
 *
 * Последовательность:
 *   1. Приложению пишут 1 в регистр 129 (уйдёт на 9600 8N2) или 131
 *      (сохранит текущую скорость). На ответ есть ~5 мс, потом перезагрузка.
 *   2. BEGIN: функция 0x10, 16 регистров по адресу 0x1000 — инфоблок 32 байта.
 *      Загрузчик сверяет подпись и стирает область приложения.
 *   3. DATA:  функция 0x10, 68 регистров по адресу 0x2000 — куски по 136 байт
 *      подряд, до конца прошивки.
 *
 * Файл .wbfw = инфоблок 32 байта + тело прошивки, добитое до кратности 136.
 * Флешер читает файл 16-битными словами и меняет в них байты местами, а Modbus
 * отдаёт регистры старшим байтом вперёд — в итоге на линии байты идут в том же
 * порядке, что и в файле. Поэтому в файл кладём прошивку как есть.
 */

/* Адреса регистров: те же, что у модулей ВБ */
#define WBFW_REG_JUMP_TO_BOOT_STANDARD_BAUD  129    /* запись 1 -> загрузчик, 9600 8N2 */
#define WBFW_REG_JUMP_TO_BOOT_CURRENT_BAUD   131    /* запись 1 -> загрузчик, скорость та же */
#define WBFW_REG_FW_VERSION                  250
#define WBFW_REG_SIGNATURE                   290    /* 12 регистров, сверяет флешер */
#define WBFW_REG_BOOTLOADER_VERSION          330    /* 8 регистров */
#define WBFW_REG_INFO_BLOCK                  0x1000 /* 16 регистров, функция 0x10 */
#define WBFW_REG_DATA_BLOCK                  0x2000 /* 68 регистров, функция 0x10 */

#define WBFW_INFO_BLOCK_SIZE   32       /* байт: 16 регистров */
#define WBFW_DATA_BLOCK_SIZE   136      /* байт: 68 регистров */

/* Скорость загрузчика жёстко задана протоколом, независимо от настроек в EEPROM */
#define WBFW_BOOT_BAUD         9600
#define WBFW_BOOT_STOPBITS     2

/* Подпись устройства. Флешер откажется писать прошивку, если она не совпала:
   ровно так чужой .wbfw не попадёт в наш модуль. */
#define WBFW_SIGNATURE         "vfd128x32"
#define WBFW_SIGNATURE_LEN     12

/* Инфоблок, 32 байта. Формат наш: и загрузчик, и генератор файла — свои,
   флешер байты только передаёт. Многобайтовые поля — старшим байтом вперёд,
   как их видит Modbus. */
struct __attribute__((packed)) wbfw_info_block {
    char     signature[WBFW_SIGNATURE_LEN];  /* 0..11  подпись, добита нулями */
    uint32_t fw_size;                        /* 12..15 размер тела, байт */
    uint32_t fw_crc32;                       /* 16..19 CRC32 тела */
    uint8_t  format_version;                 /* 20     версия формата = 1 */
    uint8_t  reserved[11];                   /* 21..31 резерв, нули */
};

#define WBFW_FORMAT_VERSION    1

/*
 * Просьба остаться в загрузчике живёт в ОЗУ по фиксированному адресу: приложение
 * пишет туда магию и уходит в перезагрузку, загрузчик проверяет и обнуляет.
 * Адрес абсолютный, а не через секцию линкера — так он не зависит от того, что
 * загрузчик и приложение собираются раздельно и разными скриптами.
 */
#if defined(STM32F411xE)
  #define BOOT_MAGIC_ADDR      0x2001FFF0UL    /* верх 128 КБ ОЗУ */
  #define BOOT_APP_BASE        0x08004000UL    /* приложение после 16 КБ загрузчика */
  #define BOOT_APP_LIMIT       0x08080000UL    /* конец 512 КБ флеша */
#elif defined(GD32E230)
  #define BOOT_MAGIC_ADDR      0x20001FF0UL    /* верх 8 КБ ОЗУ */
  #define BOOT_APP_BASE        0x08002000UL    /* приложение после 8 КБ загрузчика */
  #define BOOT_APP_LIMIT       0x08010000UL    /* конец 64 КБ флеша */
#else
  #error "не задан целевой МК"
#endif

#define BOOT_MAGIC_STAY        0xB007574FUL     /* остаться в загрузчике */
#define BOOT_MAGIC_KEEP_BAUD   0xB007CFEEUL     /* остаться, но не менять скорость */

#define BOOT_VERSION_MAJOR     1
#define BOOT_VERSION_MINOR     0
#define BOOT_VERSION_PATCH     0
