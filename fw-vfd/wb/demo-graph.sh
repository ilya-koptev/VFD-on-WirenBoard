#!/bin/sh
# Демонстрация щитка с двумя графиками на VFD-модуле 128x32.
#
# Раскладка поля (ноль по Y внизу):
#   x 0..40    две рамки с текущими значениями и единицами
#   x 42..53   шкала: четыре уровня подписями
#   x 54..56   засечки на осях против каждого уровня
#   x 56       вертикальная ось, x 56..126 — нулевая линия
#   x 58..126  сами графики, шаг 2 точки
#
# Оба графика в одной шкале 0..15, поэтому подписи уровней относятся к обоим:
#   напряжение — синусоида во всю шкалу,
#   ток — небольшой меандр в нижней части.
# Значения в рамках слева — это ровно те числа, что сейчас поставлены точками.
#
# Запуск:  sh demo-graph.sh [число проходов]   (по умолчанию 3)

DEV=${DEV:-vfd}
PASSES=${1:-3}
pub() { mosquitto_pub -h localhost -t "/devices/$DEV/controls/$1/on" -m "$2"; }

AX=56; XN=126; STEP=2          # ось и поле графиков по X
VMAX=15                        # верх шкалы: 15 единиц = 24 точки по Y
YTOP=24

# Прежний прогон снимаем по pid-файлу, а не по имени: pkill -f demo-graph.sh
# убивал бы и ту команду, которой демка запускается — в её строке то же имя.
PIDF=/run/vfd-demo.pid
[ -f "$PIDF" ] && kill "$(cat "$PIDF")" 2>/dev/null
echo $$ > "$PIDF"

# Значение шкалы -> координата Y
scale_y() { awk -v v="$1" -v vm="$VMAX" -v yt="$YTOP" 'BEGIN { printf "%d", v / vm * yt + 0.5 }'; }

pass=0
while [ "$pass" -lt "$PASSES" ]; do
    pub Mode 0; sleep 1        # очистка: стирает и строки, и графику
    pub Mode 1; sleep 1

    # --- слева рамки под значения ---
    pub Rect "0 17 40 31"; sleep 1
    pub Rect "0 0 40 15";  sleep 1
    # Число крупным шрифтом 2 (7x13), единица мелким рядом: «10,5 В» целиком
    # шрифтом 2 занимает 48 точек, а ячейка всего 40, поэтому единицы вынесены в
    # отдельные строки 6 и 7 — они статичны и перерисовке не мешают.
    pub "Place 1" "2 18 2"
    pub "Place 2" "2 2 2"
    pub "Place 6" "34 18 0"     # единица по низу числа: общая базовая линия
    pub "Place 7" "34 2 0"
    pub "Text 6" "В"
    pub "Text 7" "А"

    # --- шкала: подписи уровней и засечки против них ---
    # Подпись центруется по засечке: текст рисуется от базовой линии вверх, поэтому
    # смещаем его на половину высоты шрифта вниз. Выравниваем по правому краю у
    # самой оси, чтобы разряды стояли друг под другом. Ноль не подписываем — его
    # роль играет нулевая линия графика.
    line=3                      # подписи занимают строки 3..5
    for v in 15 10 5; do
        y=$(scale_y "$v")
        ly=$((y - 4))           # 5x8: половина высоты
        [ "$ly" -lt 0 ] && ly=0
        lx=$((54 - ${#v} * 6))  # правый край подписей — 54
        pub "Place $line" "$lx $ly 0"
        pub "Text $line" "$v"
        pub Line "54 $y 56 $y"  # засечка
        sleep 1
        line=$((line + 1))
    done

    # --- оси ---
    pub Line "$AX 0 $AX 31";  sleep 1      # вертикальная
    pub Line "$AX 0 $XN 0";   sleep 1      # нулевая линия

    # --- два графика: по две точки за шаг, без паузы между ними ---
    x=$((AX + STEP))
    i=0
    while [ "$x" -le "$XN" ]; do
        # напряжение: синусоида во всю шкалу; ток: небольшой меандр внизу
        V=$(awk -v i="$i" 'BEGIN { printf "%.1f", 10.5 + 4 * sin(i / 4.0) }')
        A=$(awk -v i="$i" 'BEGIN { printf "%.1f", (int(i / 5) % 2 ? 4.5 : 2.5) }')
        YV=$(scale_y "$V")
        YA=$(scale_y "$A")

        pub Pixel "$x $YV"      # обе точки подряд, пауза только после них
        pub Pixel "$x $YA"

        # в рамках — те же числа, что только что поставлены точками
        pub "Text 1" "$(echo "$V" | tr . ,)"
        pub "Text 2" "$(echo "$A" | tr . ,)"

        sleep 0.5
        x=$((x + STEP))
        i=$((i + 1))
    done

    echo "проход $((pass + 1)) из $PASSES дочерчен, пауза 5 с"
    sleep 5
    pass=$((pass + 1))
done

# ---------------- вторая часть: эквалайзер ----------------
# Значения идут в четырнадцать полей: семь строк текста и семь строк параметров.
# Столбцов на экране столько, сколько полей заполнено, значение = высота в точках.
echo "эквалайзер"
pub Mode 6
BARS=10                      # десять столбцов: компромисс между видом и темпом
FRAMES=${EQ_FRAMES:-60}

f=0
while [ "$f" -lt "$FRAMES" ]; do
    # спектр: у каждого столбца своя фаза, плюс дрожание — получается живая картинка
    set -- $(awk -v f="$f" -v n="$BARS" 'BEGIN {
        srand(f)
        for (i = 0; i < n; i++) {
            v = 17 + 13 * sin(f / 3.0 + i * 0.9) * (0.6 + 0.4 * rand())
            if (v < 1) v = 1; if (v > 32) v = 32
            printf "%d ", v
        }
    }')
    i=1
    for v in "$@"; do
        if [ "$i" -le 7 ]; then pub "Text $i" "$v"; else pub "Place $((i - 7))" "$v"; fi
        i=$((i + 1))
    done
    f=$((f + 1))
done

pub Mode 0
echo "демо закончено"
