#!/bin/sh
# Демонстрация щитка с графиком на VFD-модуле 128x32.
#
# Слева, в трети поля, две рамки со значениями и единицами измерения. Справа, на
# двух третях, оси координат, по которым каждые полсекунды ставится точка графика.
# Когда график дочерчен — пауза 5 с, очистка и всё заново.
#
# Показывает разделение работы: рамки, оси и точки рисуются один раз каждая и
# копятся в кадре, а значения слева перерисовываются построчно, ничего не задевая.
#
# Запуск:  sh demo-graph.sh [число проходов]   (по умолчанию 3)

DEV=${DEV:-vfd}
PASSES=${1:-3}
pub() { mosquitto_pub -h localhost -t "/devices/$DEV/controls/$1/on" -m "$2"; }

X0=46; XN=126; STEP=2          # ось X графика
Y0=2;  YN=30                   # ось Y графика

# Прежний прогон снимаем по pid-файлу, а не по имени: pkill -f demo-graph.sh
# убивал бы и ту команду, которой демка запускается — в её строке то же имя.
PIDF=/run/vfd-demo.pid
[ -f "$PIDF" ] && kill "$(cat "$PIDF")" 2>/dev/null
echo $$ > "$PIDF"

pass=0
while [ "$pass" -lt "$PASSES" ]; do
    pub Mode 0; sleep 1        # очистка: стирает и строки, и графику
    pub Mode 1; sleep 1

    # --- слева две рамки под значения ---
    pub Rect "0 16 40 31"; sleep 1
    pub Rect "0 0 40 15";  sleep 1
    pub "Place 1" "3 22 0"
    pub "Place 2" "3 5 0"
    pub "Text 1" "12,6 В"
    pub "Text 2" "1,50 А"
    sleep 1

    # --- справа оси координат ---
    pub Line "$X0 $Y0 $X0 $YN"; sleep 1     # вертикальная
    pub Line "$X0 $Y0 $XN $Y0"; sleep 1     # горизонтальная

    # --- точки графика, каждые полсекунды ---
    x=$((X0 + STEP))
    i=0
    while [ "$x" -le "$XN" ]; do
        # синусоида в пределах осей; awk, потому что sh не умеет плавающую точку
        y=$(awk -v i="$i" -v y0="$Y0" -v yn="$YN" 'BEGIN {
                a = (yn - y0 - 2) / 2
                printf "%d", y0 + 2 + a + a * sin(i / 4.0)
            }')
        pub Pixel "$x $y"
        # значения слева живут своей жизнью: обновляем на ходу
        pub "Text 1" "$(awk -v i="$i" 'BEGIN { printf "%.1f", 11.9 + (i % 6) * 0.2 }' | tr . ,) В"
        pub "Text 2" "$(awk -v i="$i" 'BEGIN { printf "%.2f", 1.2 + (i % 5) * 0.15 }' | tr . ,) А"
        sleep 0.5
        x=$((x + STEP))
        i=$((i + 1))
    done

    echo "проход $((pass + 1)) из $PASSES дочерчен, пауза 5 с"
    sleep 5
    pass=$((pass + 1))
done

pub Mode 0
echo "демо закончено"
