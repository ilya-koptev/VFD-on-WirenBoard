#!/bin/sh
# Демонстрация щитка на VFD-модуле: три рамки под первые три шрифта, в них живые
# значения с единицами измерения.
#
# Показывает главное свойство модуля: рамки рисуются один раз, размещение строк
# задаётся один раз, а дальше меняются ТОЛЬКО значения — перерисовывается место
# каждой строки, рамки и соседние строки остаются на месте.
#
# Запуск на контроллере:  sh demo-panel.sh [число обновлений]
#
# Раскладка поля 128x32, ноль по Y внизу:
#   рамка 1  x 0..41,  y 21..31   шрифт 0 (5x8)    слева сверху
#   рамка 2  x 45..92, y 19..31   шрифт 1 (6x10)   справа сверху
#   рамка 3  x 0..127, y 0..17    шрифт 2 (7x13)   снизу во всю ширину

DEV=${DEV:-vfd}
N=${1:-10}
pub() { mosquitto_pub -h localhost -t "/devices/$DEV/controls/$1/on" -m "$2"; }

echo "чистим поле"
pub Mode 0; sleep 1
pub Mode 1; sleep 1

echo "рисуем рамки"
pub Rect "0 21 41 31";  sleep 1     # примитивы копятся, поэтому рамки по очереди
pub Rect "45 19 92 31"; sleep 1
pub Rect "0 0 127 17";  sleep 1

echo "задаём размещение строк: X Y шрифт"
pub "Place 1" "2 23 0"
pub "Place 2" "48 21 1"
pub "Place 3" "4 2 2"
sleep 1

echo "обновляем значения $N раз"
i=0
while [ "$i" -lt "$N" ]; do
    # значения нарочно разной длины: видно, что прежний текст стирается ровно по
    # своему месту, а рамка не страдает
    V=$(awk -v i="$i" 'BEGIN { printf "%.1f", 11.8 + (i % 7) * 0.3 }')
    A=$(awk -v i="$i" 'BEGIN { printf "%.2f", 0.4 + (i % 5) * 0.37 }')
    T=$(awk -v i="$i" 'BEGIN { printf "%.1f", 21.5 + (i % 9) * 0.4 }')

    pub "Text 1" "$(echo "$V" | tr . ,) В"
    pub "Text 2" "$(echo "$A" | tr . ,) А"
    pub "Text 3" "$(echo "$T" | tr . ,) гр  50 Гц"
    sleep 2
    i=$((i + 1))
done

echo "готово; поле оставлено с последними значениями, очистить — Mode 0"
